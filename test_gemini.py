import os
from dotenv import load_dotenv
from google import genai

load_dotenv()

client = genai.Client(
    api_key=os.getenv("GEMINI_API_KEY")
)

response = client.models.generate_content(
    model="gemini-3.6-flash",
    contents="What are the atomic numbers of Silver and Gold? Explain in simple terms for a Class 9 student."
)

print(response.text)